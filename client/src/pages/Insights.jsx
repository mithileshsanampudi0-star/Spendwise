import { Link } from 'react-router-dom';
import { Lightbulb } from 'lucide-react';
import EmptyState from '../components/EmptyState';
import InsightCard from '../components/InsightCard';
import LoadingState from '../components/LoadingState';
import { PageHeader } from '../components/PageHeader';
import useFetch from '../hooks/useFetch';
import { useApp } from '../context/AppContext';
import { insightsApi } from '../services/api';
import { monthLabel } from '../utils/format';

export default function Insights() {
  const { month } = useApp();
  const { data, loading, error, reload } = useFetch(() => insightsApi.get({ month }), [month]);

  return (
    <>
      <PageHeader title="Financial insights" subtitle={`Rule-based observations from your own records for ${monthLabel(month)}.`} />
      {loading && !data ? <LoadingState label="Analysing your spending..." /> : error ? <LoadingState error={error} onRetry={reload} /> : !data.sufficient ? (
        <div className="card">
          <EmptyState icon={Lightbulb} title="Not enough data for insights yet" message={data.message}
            action={<Link to="/expenses" className="btn btn--primary">Add expenses</Link>} />
        </div>
      ) : (
        <>
          <div className="grid grid--2">
            {data.insights.map((i, idx) => <InsightCard key={i.type + idx} insight={i} />)}
          </div>
          <p className="muted small section">
            Insights are generated by fixed rules (highest category, month comparison, category increases, budget use and unusual spending days).
            Comparisons only appear when the previous month has data.
          </p>
        </>
      )}
    </>
  );
}
